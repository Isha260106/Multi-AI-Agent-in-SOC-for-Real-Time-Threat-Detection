"""
storage/db.py
==============
SQLite Schema + Write API

Multi-Agent SOC Project -- Stage 5: Central Event and Alert Storage

PURPOSE
-------
Provides the AlertStore class which owns:
  * Schema creation (tables + indexes)
  * Event insertion  (save_event)
  * Alert insertion  (save_alert)
  * Connection lifecycle management

TABLES
------
events
  Stores raw network-flow events as received from the producer.
  event_id is the UUID generated by the producer and is UNIQUE.

alerts
  Stores security alerts generated by the Network Detection Agent.
  alert_id is the unique identifier for each alert.
  event_id is a foreign key to events(event_id) but may be NULL
  for alerts ingested from legacy logs that predate Stage 4
  (where no event_id existed).
  Multiple alerts may share the same event_id to support future
  multi-agent outputs on the same event.

DESIGN DECISIONS
----------------
* INSERT OR IGNORE is used for events to handle re-ingestion safely.
* INSERT OR IGNORE is used for alerts (keyed on alert_id) to prevent
  duplicate rows when the consumer restarts or ingest.py is re-run.
* features_json stores all 78 model input features as a JSON blob.
  Individual feature columns are not created to keep the schema stable
  regardless of future feature set changes.
* network_context_json and class_probabilities_json are stored as JSON
  blobs for the same reason.
* WAL journal mode is enabled for better local concurrency.
* PRAGMA foreign_keys = ON is set on every new connection.
"""

