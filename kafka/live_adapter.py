def main():
    parser = argparse.ArgumentParser(
        description="Multi-Agent SOC Phase 2: Live Flow Normalization Adapter"
    )
    parser.add_argument(
        "--file", "-f",
        required=True,
        help="Path to the live CSV flow log file to process or tail."
    )
    parser.add_argument(
        "--api", "-a",
        default=DEFAULT_INGEST_URL,
        help=f"SOC Ingestion API endpoint URL (default: {DEFAULT_INGEST_URL})."
    )
    parser.add_argument(
        "--key", "-k",
        default=DEFAULT_SENSOR_KEY,
        help="Sensor Pre-Shared Key (default from SOC_SENSOR_KEY)."
    )
    parser.add_argument(
        "--duration-units", "-u",
        choices=["us", "ms", "s"],
        default="us",
        help="Flow duration time unit output by the sensor (default: 'us' microseconds)."
    )
    parser.add_argument(
        "--poll-interval", "-i",
        type=float,
        default=1.0,
        help="Polling interval in seconds for continuous tailing (default: 1.0s)."
    )
    parser.add_argument(
        "--once",
        action="store_true",
        help="Process newly available records once and exit without continuous loop."
    )
    parser.add_argument(
        "--reset-offset",
        action="store_true",
        help="Ignore and delete saved offset state to reprocess from the start of the file."
    )

    args = parser.parse_args()

    adapter = LiveFlowAdapter(duration_units=args.duration_units)
    tailer = LiveFlowTailer(
        file_path=args.file,
        adapter=adapter,
        api_url=args.api,
        api_key=args.key,
    )

    if args.reset_offset:
        tailer.reset_state()

    if args.once:
        _log.info("Executing single-pass processing on %s...", args.file)
        results = tailer.process_available_rows()
        print("\n" + "=" * 50)
        print("Live Flow Adapter Execution Summary:")
        for k, v in results.items():
            print(f"  {k:22}: {v}")
        print("=" * 50)
    else:
        tailer.tail_continuous(poll_interval=args.poll_interval)


if __name__ == "__main__":
    main()
