# Incremental CSV Tailer & HTTP Transmitter
# ---------------------------------------------------------------------------

class LiveFlowTailer:
    """
    Incrementally tails an active CSV flow log written by a network sensor
    and streams normalized events to the SOC ingestion endpoint.

    Guarantees:
    - Offset persistence across restarts (no reprocessing of historical rows).
    - Safe handling of partial writes (waits for full newline flush).
    - File rotation / truncation detection.
    - Transmission retry with exponential backoff on transient network faults.
    """

    def __init__(
        self,
        file_path: Union[str, pathlib.Path],
        adapter: Optional[LiveFlowAdapter] = None,
        offset_file: Optional[Union[str, pathlib.Path]] = None,
        api_url: str = DEFAULT_INGEST_URL,
        api_key: str = DEFAULT_SENSOR_KEY,
        http_client: Optional[httpx.Client] = None,
        max_retries: int = 3,
        backoff_factor: float = 0.5,
    ):
        self.file_path = pathlib.Path(file_path).resolve()
        self.adapter = adapter or LiveFlowAdapter()
        self.offset_file = pathlib.Path(offset_file).resolve() if offset_file else self.file_path.with_suffix(self.file_path.suffix + ".offset")
        self.api_url = api_url
        self.api_key = api_key or DEFAULT_SENSOR_KEY
        self._custom_client = http_client
        self.max_retries = max_retries
        self.backoff_factor = backoff_factor

        self.byte_offset: int = 0
        self.lines_processed: int = 0
        self.last_size: int = 0
        self.last_mtime: float = 0.0

        # Column mappings initialized when reading header
        self.feature_map: Optional[Dict[int, str]] = None
        self.metadata_map: Optional[Dict[int, str]] = None
        self.raw_header: Optional[List[str]] = None

        self._load_state()

    def _load_state(self) -> None:
        """Load tailing offset and metadata from state file."""
        if self.offset_file.is_file():
            try:
                with open(self.offset_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    self.byte_offset = data.get("byte_offset", 0)
                    self.lines_processed = data.get("lines_processed", 0)
                    self.last_size = data.get("last_size", 0)
                    self.last_mtime = data.get("last_mtime", 0.0)
                    _log.info(
                        "Loaded saved state for %s: offset=%d, lines=%d",
                        self.file_path.name, self.byte_offset, self.lines_processed
                    )
            except Exception as exc:
                _log.warning("Could not read offset file %s: %s. Starting from 0.", self.offset_file, exc)
                self.byte_offset = 0
                self.lines_processed = 0

    def _save_state(self) -> None:
        """Atomically persist tailing state to disk."""
        data = {
            "file_path": str(self.file_path),
            "byte_offset": self.byte_offset,
            "lines_processed": self.lines_processed,
            "last_size": self.last_size,
            "last_mtime": self.last_mtime,
            "updated_at": datetime.datetime.now().isoformat(),
        }
        temp_file = self.offset_file.with_suffix(".tmp")
        try:
            self.offset_file.parent.mkdir(parents=True, exist_ok=True)
            with open(temp_file, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)
            temp_file.replace(self.offset_file)
        except Exception as exc:
            _log.error("Failed to save offset state to %s: %s", self.offset_file, exc)

    def reset_state(self) -> None:
        """Reset byte offset and delete state file."""
        self.byte_offset = 0
        self.lines_processed = 0
        if self.offset_file.is_file():
            try:
                self.offset_file.unlink()
            except Exception:
                pass
        _log.info("Reset state for %s.", self.file_path.name)

    def _init_header(self, f) -> None:
        """Read and validate the header line of the CSV file."""
        pos = f.tell()
        f.seek(0)
        header_line = f.readline()
        f.seek(pos)

        if not header_line:
            return

        reader = csv.reader([header_line.strip()])
        headers = next(reader, [])
        if headers:
            self.raw_header = headers
            self.feature_map, self.metadata_map = self.adapter.build_column_mapping(headers)

    def send_event(self, payload: Dict[str, Any]) -> Tuple[bool, int, Optional[Dict[str, Any]]]:
        """
        Send a single normalized event payload to the ingestion endpoint.
        Retries on transient 5xx errors or network disconnection.

        Returns:
            (success, status_code, response_data)
        """
        headers = {
            "X-SOC-Sensor-Key": self.api_key,
            "Content-Type": "application/json",
        }

        # Use injected client if provided (e.g. Starlette TestClient), otherwise httpx.Client
        client_ctx = self._custom_client if self._custom_client else httpx.Client(timeout=10.0)

        for attempt in range(1, self.max_retries + 1):
            try:
                resp = client_ctx.post(self.api_url, json=payload, headers=headers)
                status_code = resp.status_code

                if status_code == 201:
                    return True, status_code, resp.json()
                elif status_code == 409:
                    _log.warning("Duplicate event %s already stored. Skipping.", payload.get("event_id"))
                    return True, status_code, resp.json()  # Considered resolved
                elif status_code in (400, 413, 422):
                    _log.error("Event rejected as invalid (%d): %s", status_code, resp.text)
                    return False, status_code, resp.json() if resp.text else None
                elif status_code == 401:
                    _log.error("Authentication failed (401). Check SOC_SENSOR_KEY.")
                    return False, status_code, None
                else:
                    _log.warning("Server returned %d on attempt %d/%d: %s", status_code, attempt, self.max_retries, resp.text)

            except Exception as exc:
                _log.warning("HTTP connection error on attempt %d/%d: %s", attempt, self.max_retries, exc)

            if attempt < self.max_retries:
                time.sleep(self.backoff_factor * (2 ** (attempt - 1)))

        return False, 0, None

    def read_new_lines(self) -> Generator[Tuple[int, List[str]], None, None]:
        """
        Safely reads newly appended rows from the CSV file.
        Handles partial writes by rewinding to the start of un-terminated lines.
        Detects file rotation/truncation.
        Yields (line_end_offset, parsed_csv_row).
        """
        if not self.file_path.is_file():
            return

        stat = self.file_path.stat()
        self.last_size = stat.st_size
        self.last_mtime = stat.st_mtime

        # Check for file rotation or truncation
        if stat.st_size < self.byte_offset:
            _log.warning(
                "File %s shrunk from %d to %d bytes. Rotation detected. Resetting offset.",
                self.file_path.name, self.byte_offset, stat.st_size
            )
            self.byte_offset = 0
            self.lines_processed = 0

        with open(self.file_path, "r", encoding="utf-8", errors="replace") as f:
            # 1. Initialize header if needed
            if self.feature_map is None:
                self._init_header(f)
                if self.feature_map is None:
                    return

            # 2. Seek to saved offset
            if self.byte_offset == 0:
                # Skip header row in initial run
                header_line = f.readline()
                self.byte_offset = f.tell()
                self._save_state()
            else:
                f.seek(self.byte_offset)

            # 3. Read complete new lines
            while True:
                line_start_pos = f.tell()
                line = f.readline()

                if not line:
                    break

                # Check partial line write: must end with newline
                if not (line.endswith("\n") or line.endswith("\r")):
                    # Partial line! Rewind and wait for sensor to flush the full line
                    f.seek(line_start_pos)
                    break

                line_end_pos = f.tell()
                stripped = line.strip()
                if not stripped:
                    self.byte_offset = line_end_pos
                    continue

                reader = csv.reader([stripped])
                row = next(reader, [])
                if row:
                    yield line_end_pos, row

    def process_available_rows(self, max_rows: Optional[int] = None) -> Dict[str, int]:
        """
        Process newly available CSV rows from current offset up to EOF or max_rows.
        Transmits normalized events to the ingestion endpoint and updates offset state.

        Returns:
            Dictionary with processing metrics.
        """
        stats = {
            "rows_read": 0,
            "sent_accepted": 0,
            "duplicates_skipped": 0,
            "malformed_skipped": 0,
            "transmission_errors": 0,
        }

        for end_pos, row in self.read_new_lines():
            stats["rows_read"] += 1
            seq = self.lines_processed + 1

            # 1. Normalize row
            try:
                assert self.feature_map is not None and self.metadata_map is not None
                payload = self.adapter.normalize_row_values(
                    values=row,
                    feature_map=self.feature_map,
                    metadata_map=self.metadata_map,
                    sequence=seq,
                )
            except InvalidFlowError as inv_exc:
                _log.warning("Skipping invalid flow at seq=%d: %s", seq, inv_exc)
                stats["malformed_skipped"] += 1
                self.byte_offset = end_pos
                self.lines_processed += 1
                self._save_state()
                continue
            except Exception as exc:
                _log.error("Unexpected error normalizing row at seq=%d: %s", seq, exc)
                stats["malformed_skipped"] += 1
                self.byte_offset = end_pos
                self.lines_processed += 1
                self._save_state()
                continue

            # 2. Transmit to endpoint
            success, code, _ = self.send_event(payload)

            if success:
                if code == 201:
                    stats["sent_accepted"] += 1
                elif code == 409:
                    stats["duplicates_skipped"] += 1
                # Advance and commit offset
                self.byte_offset = end_pos
                self.lines_processed += 1
                self._save_state()
            elif code in (400, 413, 422):
                stats["malformed_skipped"] += 1
                # Advance past unprocessable data
                self.byte_offset = end_pos
                self.lines_processed += 1
                self._save_state()
            else:
                stats["transmission_errors"] += 1
                _log.error("Could not transmit event %s (code=%d). Halting tailer to avoid row loss.", payload.get("event_id"), code)
                # DO NOT advance offset on transient failure! Stop processing batch.
                break

            if max_rows and stats["rows_read"] >= max_rows:
                break

        return stats

    def tail_continuous(
        self,
        poll_interval: float = 1.0,
        max_iterations: Optional[int] = None,
        stop_callback: Optional[Callable[[], bool]] = None,
    ) -> None:
        """
        Continuous tailing loop. Runs indefinitely or until stop_callback returns True.
        """
        _log.info("Starting continuous tailing on %s (interval=%.1fs)...", self.file_path, poll_interval)
        iterations = 0

        try:
            while True:
                if stop_callback and stop_callback():
                    break

                res = self.process_available_rows()
                if res["sent_accepted"] > 0 or res["transmission_errors"] > 0:
                    _log.info(
                        "Batch summary: read=%d, accepted=%d, skipped=%d, errors=%d",
                        res["rows_read"], res["sent_accepted"], res["malformed_skipped"], res["transmission_errors"]
                    )

                iterations += 1
                if max_iterations and iterations >= max_iterations:
                    break

                time.sleep(poll_interval)
        except KeyboardInterrupt:
            _log.info("Tailing stopped by user.")


