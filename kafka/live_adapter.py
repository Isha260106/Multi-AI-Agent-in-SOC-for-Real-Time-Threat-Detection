"""
kafka/live_adapter.py
=====================
Live Flow Normalization Adapter for CICFlowMeter Output.

Multi-Agent SOC Project -- Phase 2: Live Flow Normalization Adapter

PURPOSE:
--------
Normalizes raw network flow CSV records generated by external packet sensors
(such as Java CICFlowMeter v3/v4 or Python cicflowmeter) into the strictly
validated 78-feature schema required by the Multi-Agent SOC ingestion endpoint:
    `POST /api/ingest/flow`

RESPONSIBILITIES & GUARANTEES:
------------------------------
1. Canonical Schema Alignment:
   - Maps heterogeneous sensor column names (snake_case, Title Case, ISCX v3/v4)
     to the canonical 78 feature names used during model training.
2. Metadata Isolation:
   - Extracts source IP, destination IP, source port, destination port, protocol,
     timestamp, and flow identifiers as top-level metadata.
   - Guarantees network identifiers (IPs, MACs, Flow IDs) are NEVER injected as
     extra features into the model feature vector.
3. Strict Schema Validation (No Fabricated Statistics):
   - Rejects incomplete or incompatible sensor schemas (IncompatibleSchemaError).
   - Never fabricates missing statistical columns from medians.
   - Uses training-set medians solely for cell-level NaN/Inf imputation in
     otherwise complete 78-feature flow records (e.g., zero-duration division).
4. Unit Validation & Scale Verification:
   - Validates that Flow Duration and inter-arrival times conform to the
     microsecond (us) scale expected by the Random Forest model.
   - Detects and rejects negative durations (e.g., 32-bit integer overflow in
     legacy Java CICFlowMeter).
   - Supports configurable input duration scaling (us, ms, s).
5. Robust Incremental File Tailing (LiveFlowTailer):
   - Tracks file byte offsets across restarts to prevent re-ingesting old flows.
   - Handles partial line writes (waits for full newline flush).
   - Detects file rotation and truncation.
   - Safe HTTP transmission with exponential backoff retries and dead-letter handling.
"""

