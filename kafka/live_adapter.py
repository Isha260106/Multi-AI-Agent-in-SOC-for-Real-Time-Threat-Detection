def _clean_header_token(name: str) -> str:
    """Normalize a header string: lowercase, replace punctuation and slashes with spaces, strip."""
    cleaned = name.strip().lower()
    cleaned = (
        cleaned.replace("_", " ")
        .replace(".", " ")
        .replace("-", " ")
        .replace("/", " ")
        .replace("\\", " ")
    )
    return re.sub(r"\s+", " ", cleaned).strip()


