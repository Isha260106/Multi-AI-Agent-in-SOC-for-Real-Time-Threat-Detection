class LiveFlowAdapter:
    """
    Normalizes heterogeneous network flow records into the exact 78-feature
    schema and metadata payload required by POST /api/ingest/flow.
    """

    def __init__(
        self,
        prep_path: Union[str, pathlib.Path] = PREP_PATH,
        duration_units: str = "us",
        auto_detect_units: bool = False,
    ):
        """
        Initialize the adapter with training-set medians and unit preferences.

        Args:
            prep_path: Path to models/network_detection_preprocessing.pkl.
            duration_units: Flow duration scale ('us' = microseconds, 'ms' = ms, 's' = seconds).
            auto_detect_units: If True, inspects initial row values to warn on unit skew.
        """
        self.prep_path = pathlib.Path(prep_path)
        self.duration_units = duration_units.lower()
        self.auto_detect_units = auto_detect_units

        if self.duration_units not in ("us", "ms", "s"):
            raise ValueError(f"Unsupported duration_units '{duration_units}'. Must be 'us', 'ms', or 's'.")

        self.medians: Dict[str, float] = self._load_medians()
        self.canonical_features: List[str] = CANONICAL_FEATURES

    def _load_medians(self) -> Dict[str, float]:
        """Load per-feature training medians for legitimate cell-level imputation."""
        if not self.prep_path.is_file():
            _log.warning("Preprocessing metadata not found at %s. Imputation disabled.", self.prep_path)
            return {}
        try:
            prep = joblib.load(self.prep_path)
            return {k: float(v) for k, v in prep.get("medians", {}).items()}
        except Exception as exc:
            _log.warning("Could not load training medians from %s: %s", self.prep_path, exc)
            return {}

    def build_column_mapping(self, headers: List[str]) -> Tuple[Dict[int, str], Dict[int, str]]:
        """
        Analyze CSV header columns and construct index mappings to canonical features and metadata.

        Returns:
            (feature_map, metadata_map):
              feature_map: Dict[col_index -> canonical_feature_name]
              metadata_map: Dict[col_index -> metadata_field_name]

        Raises:
            IncompatibleSchemaError: If any of the required 78 canonical features
                                     cannot be mapped from the provided headers.
        """
        feature_map: Dict[int, str] = {}
        metadata_map: Dict[int, str] = {}
        mapped_features: Set[str] = set()
        unmapped_cols: List[str] = []

        for idx, col in enumerate(headers):
            token = _clean_header_token(col)

            # Check metadata first
            if token in NORMALIZED_METADATA_ALIASES:
                metadata_map[idx] = NORMALIZED_METADATA_ALIASES[token]

            # Check canonical features (Note: Dst Port and Protocol can be both metadata and feature)
            if token in NORMALIZED_FEATURE_ALIASES:
                canon_name = NORMALIZED_FEATURE_ALIASES[token]
                feature_map[idx] = canon_name
                mapped_features.add(canon_name)
            elif token not in NORMALIZED_METADATA_ALIASES and token not in NORMALIZED_IGNORED_COLUMNS:
                unmapped_cols.append(col)

        # Check completeness of the 78 canonical features
        missing_features = [f for f in self.canonical_features if f not in mapped_features]
        if missing_features:
            raise IncompatibleSchemaError(
                f"Input CSV schema is missing {len(missing_features)} of 78 required model features. "
                f"Missing: {missing_features[:10]}... Live adapter strictly rejects incomplete schemas "
                f"rather than inventing flow statistics.",
                missing_features=missing_features,
                unmapped_columns=unmapped_cols,
            )

        _log.info(
            "Schema mapped successfully: 78 canonical features identified, %d metadata fields mapped, "
            "%d extra columns ignored.",
            len(metadata_map), len(unmapped_cols)
        )
        return feature_map, metadata_map

    def normalize_row_values(
        self,
        values: List[Any],
        feature_map: Dict[int, str],
        metadata_map: Dict[int, str],
        sequence: Optional[int] = None,
        event_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Normalize a list of row values given precomputed header index mappings.
        """
        row_dict: Dict[str, Any] = {}
        meta_dict: Dict[str, Any] = {}

        # 1. Extract values by column mapping
        for idx, val in enumerate(values):
            if idx in feature_map:
                row_dict[feature_map[idx]] = val
            if idx in metadata_map:
                meta_dict[metadata_map[idx]] = val

        return self.normalize_dict(
            row_dict=row_dict,
            meta_dict=meta_dict,
            sequence=sequence,
            event_id=event_id,
        )

    def normalize_dict(
        self,
        row_dict: Dict[str, Any],
        meta_dict: Optional[Dict[str, Any]] = None,
        sequence: Optional[int] = None,
        event_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Normalize a feature dictionary into the standard `/api/ingest/flow` payload.

        Args:
            row_dict: Dictionary mapping canonical feature names (or aliases) to raw values.
            meta_dict: Optional dictionary with top-level metadata (src_ip, dst_ip, etc.).
            sequence: Monotonic sequence number.
            event_id: Optional UUID (generated if None).

        Returns:
            Normalized dictionary ready for POST /api/ingest/flow.

        Raises:
            InvalidFlowError: If numeric validation fails, duration is negative,
                              or excessive NaNs indicate corrupt flow state.
        """
        meta_dict = meta_dict or {}

        # 1. Resolve any raw alias keys in row_dict if passed directly
        resolved_features: Dict[str, Any] = {}
        for k, v in row_dict.items():
            token = _clean_header_token(k)
            if token in NORMALIZED_FEATURE_ALIASES:
                resolved_features[NORMALIZED_FEATURE_ALIASES[token]] = v
            elif token in NORMALIZED_METADATA_ALIASES and NORMALIZED_METADATA_ALIASES[token] not in meta_dict:
                meta_dict[NORMALIZED_METADATA_ALIASES[token]] = v

        # Verify all 78 canonical features exist in resolved_features
        missing = [f for f in self.canonical_features if f not in resolved_features]
        if missing:
            raise IncompatibleSchemaError(
                f"Row missing {len(missing)} required features: {missing[:10]}",
                missing_features=missing,
                unmapped_columns=[],
            )

        # 2. Scale and validate Flow Duration
        raw_duration = resolved_features.get("Flow Duration")
        try:
            duration_val = float(raw_duration)
        except (ValueError, TypeError):
            raise InvalidFlowError(f"Non-numeric Flow Duration: {raw_duration}")

        if duration_val < 0:
            raise InvalidFlowError(
                f"Negative Flow Duration detected ({duration_val}). "
                f"Likely caused by legacy 32-bit signed integer sensor overflow or timestamp skew."
            )

        # Apply duration unit conversion if sensor outputs seconds or ms
        duration_multiplier = 1.0
        if self.duration_units == "s":
            duration_multiplier = 1_000_000.0
        elif self.duration_units == "ms":
            duration_multiplier = 1_000.0

        if duration_multiplier != 1.0:
            resolved_features["Flow Duration"] = duration_val * duration_multiplier

        # 3. Numeric conversion, NaN/Inf handling, and training median imputation
        imputed_cells = 0
        normalized_features: Dict[str, float] = {}

        for feat in self.canonical_features:
            val = resolved_features[feat]
            f_val: float

            if val is None or val == "" or str(val).strip().lower() in ("nan", "null", "none"):
                imputed_cells += 1
                f_val = self.medians.get(feat, 0.0)
            else:
                try:
                    f_val = float(val)
                except (ValueError, TypeError):
                    raise InvalidFlowError(f"Non-numeric value in feature '{feat}': {val}")

                if math.isnan(f_val) or math.isinf(f_val):
                    imputed_cells += 1
                    f_val = self.medians.get(feat, 0.0)

            normalized_features[feat] = f_val

        # Reject row if too many features had to be imputed
        if imputed_cells > MAX_ALLOWED_IMPUTATIONS_PER_ROW:
            raise InvalidFlowError(
                f"Flow record contains {imputed_cells} NaN/Inf values, exceeding maximum "
                f"tolerance of {MAX_ALLOWED_IMPUTATIONS_PER_ROW}. Discarding corrupt flow record."
            )

        # 4. Extract and preserve metadata
        src_ip = meta_dict.get("src_ip")
        dst_ip = meta_dict.get("dst_ip")
        src_port = meta_dict.get("src_port")
        if src_port is not None:
            try:
                src_port = int(float(src_port))
            except Exception:
                src_port = None

        dst_port = meta_dict.get("dst_port")
        if dst_port is None:
            dst_port = int(normalized_features["Dst Port"])
        else:
            try:
                dst_port = int(float(dst_port))
            except Exception:
                dst_port = int(normalized_features["Dst Port"])

        protocol = meta_dict.get("protocol")
        if protocol is None:
            protocol = int(normalized_features["Protocol"])
        else:
            try:
                protocol = int(float(protocol))
            except Exception:
                protocol = str(protocol)

        timestamp = meta_dict.get("timestamp") or datetime.datetime.now().isoformat()
        actual_label = meta_dict.get("actual_label")

        # 5. Assemble final ingestion payload
        # CRITICAL: src_ip, dst_ip, src_port, and flow_id are top-level metadata only!
        # normalized_features contains strictly the 78 canonical metrics.
        return {
            "event_id": event_id or f"sensor-{uuid.uuid4()}",
            "timestamp": str(timestamp),
            "source": "live_sensor",
            "sequence": sequence or 0,
            "src_ip": str(src_ip) if src_ip else None,
            "dst_ip": str(dst_ip) if dst_ip else None,
            "src_port": src_port,
            "dst_port": dst_port,
            "protocol": protocol,
            "actual_label": str(actual_label) if actual_label else None,
            "features": normalized_features,
        }


